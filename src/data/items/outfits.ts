/** Classify a hex color into a palette family for cohesion scoring. */
function colorFamily(hex: string): PaletteFamily {
  if (hex === 'gold' || hex === 'rose') return 'warm';
  if (hex === 'silver') return 'cool';
  const m = hex.replace('#', '');
  if (m.length < 6) return 'neutral';
  const r = parseInt(m.slice(0, 2), 16);
  const g = parseInt(m.slice(2, 4), 16);
  const b = parseInt(m.slice(4, 6), 16);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 510;
  const s = max === min ? 0 : (max - min) / (255 - Math.abs(max + min - 255));
  if (s < 0.16 || l < 0.1 || l > 0.93) return 'neutral';
  const hue = (() => {
    const d = max - min;
    if (d === 0) return 0;
    if (max === r) return ((g - b) / d) % 6;
    if (max === g) return (b - r) / d + 2;
    return (r - g) / d + 4;
  })();
  const h = ((hue * 60) + 360) % 360;
  if (l > 0.72 && s < 0.55) return 'pastel';
  if (l < 0.42 && s > 0.45) return 'jewel';
  if (h >= 20 && h <= 70) return 'earth';
  if (h > 70 && h < 200) return 'cool';
  return 'warm';
}

export function variant(
  id: string,
  color: string,
  color2?: string,
  tags?: Variant['tags'],
  name = 'Signature',
): Variant {
  return {
    id,
    name,
    colors: color2 ? { primary: color, secondary: color2 } : { primary: color },
    family: colorFamily(color),
    tags,
  };
}

