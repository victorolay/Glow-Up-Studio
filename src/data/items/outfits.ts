/** Convenience: variant lookup with fallback to first variant. */
export function outfitVariant(item: OutfitItem, variantId?: string): Variant | undefined {
  if (item.variants.length === 0) return undefined;
  return item.variants.find((v) => v.id === variantId) ?? item.variants[0];
}
